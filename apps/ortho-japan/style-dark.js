// 「Quiet Mono Dark」── style-mono.js の黒基調版。構造（レイヤ・フィルタ・幅）は一切持たず、
// 色対応表だけを持って mono を機械変換する＝mono の改修（幅・フィルタ・新レイヤ）に自動追従し drift しない。
// 対応表に無い色が mono に増えたら console.warn で知らせる（黙って白い色が夜地図に紛れない）。
//
// 色決めの原則（mono と同じ掟の夜版）：
//  - 薄さは opacity でなく実色で作る（重なりムラ防止）＝「紙へ寄せる」のブレンド先が暗い紙に変わるので全色再計算。
//  - 白地図の「濃い＝主役」は夜地図では「明るい＝主役」に反転：道路の格は明度の階段を逆向きに登る。
//  - 点火色（緑/青/深紅）は同じ色相のまま明度を一段持ち上げる＝チップの意味（色＝地図上の色）を保つ。
import mono from "./style-mono.js";

const PAPER = "#191d24";   // 夜の紙（寒色の暗灰＝quiet-mono の寒色tintと同族。宇宙 #080a12 より一段明るい＝球の輪郭が残る）
const MAP = {
	"#f6f6f4": PAPER,       // 紙（bg・road-face の白帯・注記ハロー）
	"#e2e6ea": "#090c12",   // 海（z8+ の一律水色）：紙より明確に深い夜の海＝海岸線が塗りの明暗差で立つ（宇宙#080a12とほぼ同深度）
	"#aecbe6": "#2b6d80",   // 水系点火（WA面・河川中心線）：青緑(シアン寄り)＝道路の青と色相を分ける（夜は水と道路が被る指摘＝家族より）
	"#ececea": "#21252d",   // 建築物：紙より一段明るい気配（白地図の「一段暗い」の反転）
	"#c9c9c7": "#3e444d",   // 鉄道 土台
	"#bdbdba": "#5c626b",   // 道路 高速（土台の最上位＝最も明るい。それでも土台は囁き＝紙+黒の中間まで沈める）
	"#c6c6c3": "#4f555e",   // 道路 国道 ＋ 道路縁(RdEdg)：暗い路面を少し明るい縁が縁取る
	"#d2d2cf": "#424851",   // 道路 都道府県道
	"#dcdcda": "#363c44",   // 道路 その他（既定）
	"#e0e0dd": "#31373f",   // 道路 市区町村道
	"#cececb": "#2e343c",   // 行政界 土台
	"#aa7878": "#a03a42",   // 行政界 点火：深紅（夜は紙へ寄せず色をそのまま立てる＝細線0.8pxでも紅と読める）
	"#4b9e6a": "#58b57b",   // 鉄道点火 JR
	"#8eb43e": "#9cc44e",   // 鉄道点火 私鉄等
	"#2f6cad": "#3f6fd8",   // 道路点火 高速：濃い青（水系のくすんだ青に対し彩度高い青で「道路」と読ませる）
	"#8fb2d6": "#8560d0",   // 道路点火 国道：紫（水系の青と被る主犯を色相ごと分離＝夜のみの逸脱・可読性優先。行政界は深紅で紫は空き）
	"#7aa8cf": "#4a7699",   // 航路
	"#86867f": "#9aa1a9",   // 注記の文字（ハローは紙色＝PAPER が受ける）
};

// 再帰置換：式言語（match/interpolate…の配列）の中の hex 文字列だけ差し替える。
function swap(v) {
	if (typeof v === "string") {
		if (MAP[v]) return MAP[v];
		if (/^#[0-9a-f]{3,8}$/i.test(v)) console.warn(`[style-dark] 対応表に無い色 ${v}＝monoのまま`);
		return v;
	}
	if (Array.isArray(v)) return v.map(swap);
	if (v && typeof v === "object") return Object.fromEntries(Object.entries(v).map(([k, x]) => [k, swap(x)]));
	return v;
}

export default { ...swap(mono), name: "Quiet Mono Dark" };
