// 泉質の原文 → 療養泉の 10 分類（環境省「鉱泉分析法指針」）。複数該当は原文の出現順に ";" 区切り。
// 例: 「ナトリウム・カルシウム-硫酸塩・塩化物泉」→ "硫酸塩泉;塩化物泉"、「酸性泉（酸性低張性高温泉）」→ "酸性泉"
const CLASSES = [
  ["単純温泉", /単純温泉|単純泉|単純(冷)?鉱泉|アルカリ性単純/],
  ["塩化物泉", /塩化物|食塩泉|塩類泉|強塩泉/],
  ["炭酸水素塩泉", /炭酸水素塩|重曹泉|重炭酸土類泉|炭酸水素/],
  ["硫酸塩泉", /硫酸塩|石膏泉|正苦味泉|芒硝泉|苦味泉/],
  ["二酸化炭素泉", /二酸化炭素|炭酸泉/],
  ["含鉄泉", /含鉄|鉄泉|緑ばん泉|緑礬泉|鉄\(II\)/],
  ["酸性泉", /酸性泉|明ばん泉|明礬泉|(^|[^弱])酸性[・\-－‐]|(^|[^弱])酸性(?=[^性]*(含|泉))/],
  ["含よう素泉", /含よう素|含ヨウ素|ヨウ素泉|よう素泉|含ヨード/],
  ["硫黄泉", /硫黄|硫化水素/],
  ["放射能泉", /放射能|ラジウム|ラドン/],
];
export function qualityClass(q) {
  if (!q) return "";
  // 括弧内の液性・張性・泉温（「酸性低張性高温泉」「低張性弱アルカリ性温泉」等）は分類の手がかりにしない。
  // ただし「旧泉質名: 食塩泉」のような括弧は残す。
  const t = q.replace(/[（(][^（）()]*[）)]/g, m => /張性|高温泉|低温泉|温泉\)|冷鉱泉|中性|アルカリ性(?!単純)|弱酸性/.test(m) && !/旧泉質|旧名/.test(m) ? "" : m);
  return CLASSES.map(([k, re]) => { const m = t.match(re); return m ? [m.index, k] : null; }).filter(Boolean).sort((x, y) => x[0] - y[0]).map(x => x[1]).join(";");
}
